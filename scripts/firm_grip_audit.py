"""How often does Haiku set the firm grip on `stack`, and what happens when it does or does not? (held-out episodes, corrected simulator, run seeds 20 to 29)

    python scripts/firm_grip_audit.py [runs] > results/firm_grip_audit.md

Counts an episode as 'firm' if any call in it passes grip_level = firm. A mechanism check on the raw tool-call logs; the other route the notebook arms find is a 45 degree
turn of the hand (yaw_offset_deg), also counted. In every turn-only episode the model also set speed slow (and in some a grasp height of 0.5 or its own hand placement with move_to and
open_gripper), a combination the scripted one-setting-at-a-time audit (results/settings_audit.md: the turn alone builds the tower in 10 of 20) did not test."""
import glob
import json
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else "runs")
H = "claude-haiku-5-5"
ARMS = [("starts fresh", "rep_fixed", "none"), ("generic hint", "hint_generic", "hint_generic"), ("hint naming the fix", "hint", "hint"),
        ("Fable's notebook, no practice", "prior", "prior"), ("Sonnet's notebook, no practice", "borrowed_sonnet", "borrowed"), ("own notebook", "rep_fixed", "notebook")]


def episodes(folder, cond):
    for f in sorted(glob.glob(str(root / folder / f"{H}__stack__{cond}__quirk__*.jsonl"))):
        for line in Path(f).read_text().splitlines()[1:]:
            r = json.loads(line)
            if "result" in r and r.get("phase") == "eval":
                yield r


rows = []
for name, folder, cond in ARMS:
    eps = list(episodes(folder, cond))
    if not eps:
        continue
    firm = [any((c.get("args") or {}).get("grip_level") == "firm" for c in r["log"]) for r in eps]
    yaw = [any(abs((c.get("args") or {}).get("yaw_offset_deg") or 0) == 45 for c in r["log"]) for r in eps]
    ok = [bool(r["result"]["success"]) for r in eps]
    both = lambda a, b: sum(1 for x, y in zip(a, b) if x and y)
    rows.append((name, len(eps), sum(ok), sum(firm), both(firm, ok), sum(1 for f_, y in zip(firm, yaw) if y and not f_), sum(1 for f_, y, o in zip(firm, yaw, ok) if y and not f_ and o),
                 sum(1 for f_, y in zip(firm, yaw) if not f_ and not y), sum(1 for f_, y, o in zip(firm, yaw, ok) if not f_ and not y and o)))
print("# Firm grip on `stack`: how often Haiku sets it, and what follows\n")
print("Held-out `stack` episodes of Claude Haiku 5.5 on the corrected simulator (run seeds 20 to 29, 4 layouts per run, 40 per arm). An episode counts as *firm* if any call in it passes `grip_level` firm; *turned hand only* means a 45 degree `yaw_offset_deg` without a firm grip; *neither* means the default grip with no turn. In every turn-only episode the model also set `speed` slow (some also a grasp height of 0.5 or placed the cube by hand with `move_to` and `open_gripper`), a combination the one-setting-at-a-time settings audit did not test. Generated by `scripts/firm_grip_audit.py` from the raw tool-call logs.\n")
print("| arm | episodes | solved | firm grip | solved with firm grip | turned hand only | solved with turned hand only | neither | solved with neither |")
print("|---|---|---|---|---|---|---|---|---|")
for r in rows:
    print("| " + " | ".join(str(x) for x in r) + " |")
